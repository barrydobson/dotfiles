#!/bin/bash

# =============================================================================
# Dotfiles Bootstrap
# =============================================================================
# Detects the OS, installs dependencies, stows configs, and installs tools.

set -eo pipefail

DOTFILES_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# shellcheck source=./install/common.sh
source "${DOTFILES_DIR}/install/common.sh"

# Packages stowed on every platform
COMMON_PACKAGES=(
  agents
  atuin
  claude
  codex
  editorconfig
  eza
  herdr-core
  git
  mise
  nvim
  starship
  tmux
  worktrunk
  yamllint
  zsh
)

# Packages stowed on macOS only
MAC_PACKAGES=(
  1Password
  cli-proxy-api
  homebrew
  ghostty
  herdr-app
  k9s
  lazygit
  ssh
  vscode
  zed
)

detect_os() {
  if [[ "$(uname)" == "Darwin" ]]; then
    echo "macos"
    return
  fi

  if [[ ! -f /etc/os-release ]]; then
    print_error "Cannot detect OS: no /etc/os-release" >&2
    exit 1
  fi

  # shellcheck disable=SC1091
  source /etc/os-release
  # ID_LIKE catches the Debian derivatives (Mint, Pop!_OS, Kali, ...)
  case " ${ID} ${ID_LIKE:-} " in
  *" debian "* | *" ubuntu "*) echo "debian" ;;
  *) echo "${ID}" ;;
  esac
}

# Install packages from Homebrew. This is called after stowing, so the Brewfile should be in place.
install_homebrew_packages() {
  if [[ ! -f "${HOME}/.Brewfile" ]]; then
    print_warning "No Brewfile found, skipping package installation"
    return
  fi

  print_status "Installing packages from Homebrew..."
  brew bundle install --file "${HOME}/.Brewfile"
  print_success "Homebrew packages installed"
}

setup_macos_1password() {
  if ! command -v op >/dev/null 2>&1; then
    print_warning "1Password CLI is not installed, skipping SSH agent socket"
    return
  fi

  mkdir -p "${HOME}/.1password"
  ln -sfn "${HOME}/Library/Group Containers/2BUA8C4S2C.com.1password/t/agent.sock" \
    "${HOME}/.1password/agent.sock"
  print_success "1Password SSH agent socket linked"
}

# Codex has no @import, so inline the private files CLAUDE.md imports. Output is gitignored.
generate_codex_agents_md() {
  local src="${DOTFILES_DIR}/packages/claude/.claude"
  local out="${DOTFILES_DIR}/packages/codex/.codex/AGENTS.md"
  local f
  # Drop @imports and <!-- claude-only --> blocks naming tools Codex lacks
  local strip=(-e '/^@/d' -e '/^<!-- claude-only -->$/,/^<!-- \/claude-only -->$/d')

  {
    echo "<!-- Generated by install.sh from packages/claude/.claude. Edit those files, not this one. -->"
    sed "${strip[@]}" "${src}/CLAUDE.md"
    for f in me.md work.md; do
      if [[ -f "${src}/${f}" ]]; then
        printf '\n'
        sed "${strip[@]}" "${src}/${f}"
      fi
    done
  } >"${out}"
  print_success "Generated Codex AGENTS.md"
}

# Apps that write to their own config are not stowed. See merge_config and seed_config.
sync_app_configs() {
  merge_config toml "${DOTFILES_DIR}/install/codex-config.toml" "${HOME}/.codex/config.toml"
  merge_config json "${DOTFILES_DIR}/install/claude-settings.json" "${HOME}/.claude/settings.json"
  seed_config "${DOTFILES_DIR}/install/ccstatusline-settings.json" "${HOME}/.config/ccstatusline/settings.json"
}

# Claude keeps user MCP servers in ~/.claude.json, not settings.json. Codex has none.
add_claude_mcp_server() {
  if ! claude mcp get "$1" >/dev/null 2>&1; then
    claude mcp add-json -s user "$1" "$2"
  fi
}

add_claude_mcp_servers() {
  add_claude_mcp_server granola '{"type":"http","url":"https://mcp.granola.ai/mcp"}'
  add_claude_mcp_server groundcover '{"type":"http","url":"https://mcp.groundcover.com/api/mcp"}'
  add_claude_mcp_server notion '{"type":"http","url":"https://mcp.notion.com/mcp"}'
  add_claude_mcp_server vault "{\"command\":\"npx\",\"args\":[\"-y\",\"@modelcontextprotocol/server-filesystem\",\"${HOME}/vault/\"]}"
  print_success "Claude MCP servers in place"
}

# Claude gets its plugins from enabledPlugins in settings.json. Both commands are no-ops
# when already done.
add_codex_plugins() {
  codex plugin marketplace add barrydobson/skills
  codex plugin marketplace add DietrichGebert/ponytail
  codex plugin add barrydobson-skills@barrydobson
  codex plugin add ponytail@ponytail
}

# Codex reads hooks only from hooks.json, which other tools may also write, so append ours
# rather than stow it. Same hooks as SessionStart in the Claude settings.json.
add_codex_session_hook() {
  local file="${HOME}/.codex/hooks.json" yq
  if grep -qs 'hc-context.sh' "${file}"; then
    return
  fi
  yq=$(command -v yq || mise which yq) || {
    print_warning "yq is not installed, skipping the Codex SessionStart hook"
    return
  }
  [[ -s "${file}" ]] || echo '{}' >"${file}"
  # $HOME is expanded by Codex when the hook runs
  # shellcheck disable=SC2016
  HOOK='{"hooks":[
    {"type":"command","command":"bash \"$HOME/.claude/hooks/systems-note-context.sh\"","timeout":5},
    {"type":"command","command":"bash \"$HOME/.claude/hooks/hc-context.sh\"","timeout":5}]}' \
    "${yq}" -i -p json -o json -I 2 '.hooks.SessionStart += [env(HOOK)]' "${file}"
  print_success "Added the Codex SessionStart hook"
}

# Stow links each skill into these, so they must be real dirs, not folded into one link
unfold_skill_targets() {
  local dir
  for dir in "${HOME}/.claude/skills" "${HOME}/.agents/skills"; do
    if [[ -L "${dir}" ]]; then
      rm "${dir}"
    fi
    mkdir -p "${dir}"
  done
}

# The vault skills name Tote internals, so they stay in the vault and are linked from it.
link_vault_skills() {
  local skill src
  for skill in vault-query systems-memory-check; do
    src="${HOME}/vault/.claude/skills/${skill}"
    if [[ -d "${src}" ]]; then
      ln -sfn "${src}" "${HOME}/.claude/skills/${skill}"
    else
      print_warning "no vault skill at ${src}, skipping"
    fi
  done
}

# Real dirs stop stow folding them into one symlink, which would pull runtime state and
# auth.json into the repo. ~/.codex/rules too: Codex writes default.rules there next to
# the stowed dotfiles.rules.
prepare_agent_dirs() {
  mkdir -p "${HOME}/.claude" "${HOME}/.codex/rules" "${HOME}/.config/herdr-core"
  generate_codex_agents_md
  unfold_skill_targets
  # skillshare was removed; drop its stale stow link
  if [[ -L "${HOME}/.config/skillshare" && ! -e "${HOME}/.config/skillshare" ]]; then
    rm "${HOME}/.config/skillshare"
  fi
}

# A fixed path to the clone, wherever it was cloned, for pulling updates.
link_dotfiles_dir() {
  local link="${HOME}/.dotfiles"
  if [[ "${DOTFILES_DIR}" == "${link}" ]]; then
    return
  fi
  if [[ -e "${link}" && ! -L "${link}" ]]; then
    print_warning "${link} exists and is not a symlink; leaving it"
    return
  fi
  ln -sfn "${DOTFILES_DIR}" "${link}"
}

install_linux_extras() {
  install_starship
  install_1password_cli
}

# A key made on this machine, so nothing secret has to reach it. Commits sign once the
# public key is registered with GitHub (printed in the checklist).
setup_linux_git_signing() {
  local local_config="${HOME}/.config/git/.gitconfig-local"
  local key="${HOME}/.ssh/id_ed25519_signing"

  if git config --file "${local_config}" --get user.signingkey >/dev/null 2>&1; then
    print_status "Git signing key already configured"
    return
  fi
  mkdir -p "${HOME}/.ssh"
  chmod 700 "${HOME}/.ssh"
  if [[ ! -f "${key}" ]]; then
    ssh-keygen -q -t ed25519 -N "" -C "git-signing@$(hostname)" -f "${key}"
  fi
  git config --file "${local_config}" user.signingkey "${key}.pub"
  print_success "Git signing key created: ${key}.pub"
}

# gh setup-git would write to the stowed ~/.config/git/config, so set the helper locally
setup_linux_git_credentials() {
  local local_config="${HOME}/.config/git/.gitconfig-local"
  git config --file "${local_config}" 'credential.https://github.com.helper' '!gh auth git-credential'
  git config --file "${local_config}" 'credential.https://gist.github.com.helper' '!gh auth git-credential'
}

print_linux_checklist() {
  # Shown to the user, not expanded
  # shellcheck disable=SC2088
  local local_config="~/.config/git/.gitconfig-local"
  echo
  print_status "Finish by hand (logins and identity):"
  if ! git config --file "${HOME}/.config/git/.gitconfig-local" --get user.email >/dev/null 2>&1; then
    echo "  git config --file ${local_config} user.name  \"Your Name\""
    echo "  git config --file ${local_config} user.email \"you@example.com\""
  fi
  echo "  gh auth login"
  echo "  gh ssh-key add ~/.ssh/id_ed25519_signing.pub --type signing --title \"$(hostname)\""
  echo "  claude                      # log in"
  echo "  codex login --device-auth"
  echo "  codex, then /hooks          # approve the SessionStart hook"
}

main() {
  local os
  os=$(detect_os)
  print_status "Detected OS family: ${os}"

  export PATH="${HOME}/.local/bin:${PATH}"
  link_dotfiles_dir

  case "${os}" in
  macos)
    bash "${DOTFILES_DIR}/install/mac.sh"
    prepare_agent_dirs
    stow_packages "${COMMON_PACKAGES[@]}" "${MAC_PACKAGES[@]}"
    install_homebrew_packages
    setup_macos_1password
    ;;
  debian)
    bash "${DOTFILES_DIR}/install/ubuntu.sh"
    prepare_agent_dirs
    stow_packages "${COMMON_PACKAGES[@]}"
    install_linux_extras
    ;;
  *)
    print_error "Unsupported OS: ${os}. Supported: macos, debian/ubuntu"
    exit 1
    ;;
  esac

  install_claude_code
  install_codex
  install_herdr_core
  install_tpm

  if ! command -v mise >/dev/null 2>&1; then
    print_error "mise is not on PATH, cannot install tool versions"
    exit 1
  fi
  MISE_AQUA_GITHUB_ATTESTATIONS=false mise install
  # After the agent CLIs, and after mise install, which provides yq on Linux
  add_claude_mcp_servers
  add_codex_plugins
  add_codex_session_hook
  link_vault_skills
  # Last: codex plugin writes to config.toml too, and a merge before it would rewrite
  # the file again on the next run.
  sync_app_configs

  if [[ "${os}" == "debian" ]]; then
    setup_linux_git_signing
    setup_linux_git_credentials
    print_linux_checklist
  fi
  print_success "Done! Restart your terminal or run: exec zsh"
}

main "$@"
