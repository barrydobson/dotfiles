#!/bin/bash

# =============================================================================
# Dotfiles Bootstrap
# =============================================================================
# Detects the OS, installs dependencies, stows configs, and installs tools.

set -eo pipefail

DOTFILES_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# shellcheck source=./install/common.sh
source "${DOTFILES_DIR}/install/common.sh"

# Packages stowed on every platform
COMMON_PACKAGES=(
  atuin
  ccstatusline
  claude
  codex
  editorconfig
  eza
  herdr
  herdr-core
  git
  mise
  nvim
  skillshare
  starship
  tmux
  worktrunk
  yamllint
  zsh
)

# Packages stowed on macOS only
MAC_PACKAGES=(
  1Password
  cli-proxy-api
  homebrew
  ghostty
  herdr-app
  k9s
  lazygit
  skills
  ssh
  vscode
  zed
)

detect_os() {
  if [[ "$(uname)" == "Darwin" ]]; then
    echo "macos"
    return
  fi

  if [[ ! -f /etc/os-release ]]; then
    print_error "Cannot detect OS: no /etc/os-release" >&2
    exit 1
  fi

  # shellcheck disable=SC1091
  source /etc/os-release
  # ID_LIKE catches the Debian derivatives (Mint, Pop!_OS, Kali, ...)
  case " ${ID} ${ID_LIKE:-} " in
  *" debian "* | *" ubuntu "*) echo "debian" ;;
  *) echo "${ID}" ;;
  esac
}

# Install packages from Homebrew. This is called after stowing, so the Brewfile should be in place.
install_homebrew_packages() {
  if [[ ! -f "${HOME}/.Brewfile" ]]; then
    print_warning "No Brewfile found, skipping package installation"
    return
  fi

  print_status "Installing packages from Homebrew..."
  brew bundle install --file "${HOME}/.Brewfile"
  print_success "Homebrew packages installed"
}

setup_macos_1password() {
  if ! command -v op >/dev/null 2>&1; then
    print_warning "1Password CLI is not installed, skipping SSH agent socket"
    return
  fi

  mkdir -p "${HOME}/.1password"
  ln -sfn "${HOME}/Library/Group Containers/2BUA8C4S2C.com.1password/t/agent.sock" \
    "${HOME}/.1password/agent.sock"
  print_success "1Password SSH agent socket linked"
}

# Codex has no @import, so inline the private files CLAUDE.md imports. Output is gitignored.
generate_codex_agents_md() {
  local src="${DOTFILES_DIR}/packages/claude/.claude"
  local out="${DOTFILES_DIR}/packages/codex/.codex/AGENTS.md"
  local f
  # Drop @imports and <!-- claude-only --> blocks naming tools Codex lacks
  local strip=(-e '/^@/d' -e '/^<!-- claude-only -->$/,/^<!-- \/claude-only -->$/d')

  {
    echo "<!-- Generated by install.sh from packages/claude/.claude. Edit those files, not this one. -->"
    sed "${strip[@]}" "${src}/CLAUDE.md"
    for f in me.md work.md; do
      if [[ -f "${src}/${f}" ]]; then
        printf '\n'
        sed "${strip[@]}" "${src}/${f}"
      fi
    done
  } >"${out}"
  print_success "Generated Codex AGENTS.md"
}

# Codex writes trust and state into config.toml, so it is not stowed. Merge the common
# settings into it instead: common keys win, everything else in the file is kept.
# Needs no sudo, unlike Codex's /etc/codex/config.toml layer.
sync_codex_config() {
  local dest="${HOME}/.codex/config.toml"
  local common="${DOTFILES_DIR}/install/codex-config.toml"
  local yq tmp

  # On Linux yq comes from mise, whose shims may not be on PATH yet
  yq=$(command -v yq || mise which yq 2>/dev/null) || {
    print_warning "yq is not installed, skipping Codex config merge"
    return
  }

  mkdir -p "${HOME}/.codex"
  # An old stow link would make the write land in the repo
  if [[ -L "${dest}" ]]; then
    rm "${dest}"
  fi
  [[ -e "${dest}" ]] || : >"${dest}"

  tmp=$(mktemp)
  # $f is a yq variable. Comments are dropped so the common file's header is not copied in.
  # shellcheck disable=SC2016
  "${yq}" ea -p toml -o toml '(. as $f ireduce ({}; . * $f)) | ... comments = ""' "${dest}" "${common}" >"${tmp}"
  if cmp -s "${tmp}" "${dest}"; then
    rm "${tmp}"
    print_status "Codex config.toml already has the common settings"
    return
  fi
  mv "${tmp}" "${dest}"
  chmod 600 "${dest}"
  print_success "Merged common settings into Codex config.toml"
}

# skillshare links each skill into these, so they must be real dirs, not old stow folds
unfold_skill_targets() {
  local dir
  for dir in "${HOME}/.claude/skills" "${HOME}/.agents/skills"; do
    if [[ -L "${dir}" ]]; then
      rm "${dir}"
    fi
    mkdir -p "${dir}"
  done
}

sync_skillshare() {
  if ! command -v skillshare >/dev/null 2>&1; then
    print_warning "skillshare is not installed, skipping skill, MCP and hook sync"
    return
  fi
  skillshare sync --all --no-tui
  # --all leaves out plugins
  skillshare sync plugins --no-tui
  print_success "skillshare synced"
}

# Real dirs stop stow folding them into one symlink, which would pull runtime state and
# auth.json into the repo. ~/.codex/rules too: Codex writes default.rules there next to
# the stowed dotfiles.rules.
prepare_agent_dirs() {
  mkdir -p "${HOME}/.claude" "${HOME}/.codex/rules" "${HOME}/.config/herdr-core"
  generate_codex_agents_md
  unfold_skill_targets
}

install_linux_extras() {
  install_starship
  install_1password_cli
  # macOS gets skillshare from the Brewfile
  install_skillshare
}

# A key made on this machine, so nothing secret has to reach it. Commits sign once the
# public key is registered with GitHub (printed in the checklist).
setup_linux_git_signing() {
  local local_config="${HOME}/.config/git/.gitconfig-local"
  local key="${HOME}/.ssh/id_ed25519_signing"

  if git config --file "${local_config}" --get user.signingkey >/dev/null 2>&1; then
    print_status "Git signing key already configured"
    return
  fi
  mkdir -p "${HOME}/.ssh"
  chmod 700 "${HOME}/.ssh"
  if [[ ! -f "${key}" ]]; then
    ssh-keygen -q -t ed25519 -N "" -C "git-signing@$(hostname)" -f "${key}"
  fi
  git config --file "${local_config}" user.signingkey "${key}.pub"
  print_success "Git signing key created: ${key}.pub"
}

# gh setup-git would write to the stowed ~/.config/git/config, so set the helper locally
setup_linux_git_credentials() {
  local local_config="${HOME}/.config/git/.gitconfig-local"
  git config --file "${local_config}" 'credential.https://github.com.helper' '!gh auth git-credential'
  git config --file "${local_config}" 'credential.https://gist.github.com.helper' '!gh auth git-credential'
}

print_linux_checklist() {
  # Shown to the user, not expanded
  # shellcheck disable=SC2088
  local local_config="~/.config/git/.gitconfig-local"
  echo
  print_status "Finish by hand (logins and identity):"
  if ! git config --file "${HOME}/.config/git/.gitconfig-local" --get user.email >/dev/null 2>&1; then
    echo "  git config --file ${local_config} user.name  \"Your Name\""
    echo "  git config --file ${local_config} user.email \"you@example.com\""
  fi
  echo "  gh auth login"
  echo "  gh ssh-key add ~/.ssh/id_ed25519_signing.pub --type signing --title \"$(hostname)\""
  echo "  claude                      # log in"
  echo "  codex login --device-auth"
  echo "  codex, then /hooks          # approve the skillshare SessionStart hook"
  echo "  codex mcp login <server>    # for each HTTP MCP server in: codex mcp list"
}

main() {
  local os
  os=$(detect_os)
  print_status "Detected OS family: ${os}"

  export PATH="${HOME}/.local/bin:${PATH}"

  case "${os}" in
  macos)
    bash "${DOTFILES_DIR}/install/mac.sh"
    prepare_agent_dirs
    stow_packages "${COMMON_PACKAGES[@]}" "${MAC_PACKAGES[@]}"
    install_homebrew_packages
    setup_macos_1password
    ;;
  debian)
    bash "${DOTFILES_DIR}/install/ubuntu.sh"
    prepare_agent_dirs
    stow_packages "${COMMON_PACKAGES[@]}"
    install_linux_extras
    ;;
  *)
    print_error "Unsupported OS: ${os}. Supported: macos, debian/ubuntu"
    exit 1
    ;;
  esac

  install_claude_code
  install_codex
  install_herdr_core
  install_tpm

  if ! command -v mise >/dev/null 2>&1; then
    print_error "mise is not on PATH, cannot install tool versions"
    exit 1
  fi
  MISE_AQUA_GITHUB_ATTESTATIONS=false mise install
  # After the agent CLIs: plugin sync installs into Codex
  sync_skillshare
  # Last: skillshare writes to config.toml too, and a merge before it would rewrite the
  # file again on the next run. After mise install, which provides yq on Linux.
  sync_codex_config

  if [[ "${os}" == "debian" ]]; then
    setup_linux_git_signing
    setup_linux_git_credentials
    print_linux_checklist
  fi
  print_success "Done! Restart your terminal or run: exec zsh"
}

main "$@"
